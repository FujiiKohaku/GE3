# Regenerate the two static meshes used by FearWorm's head HP ring.
$ErrorActionPreference = 'Stop'
$outputDirectory = Join-Path $PSScriptRoot '../resources/Models/Boss/FearWorm/HpGear'
[IO.Directory]::CreateDirectory($outputDirectory) | Out-Null
$culture = [Globalization.CultureInfo]::InvariantCulture

function New-Point([double]$radius, [double]$angle, [double]$depth) {
    return ,@(($radius * [Math]::Cos($angle)), ($radius * [Math]::Sin($angle)), $depth)
}

function Add-Quad($a, $b, $c, $d, [bool]$isBackCopy = $false) {
    $u = @(($b[0]-$a[0]), ($b[1]-$a[1]), ($b[2]-$a[2]))
    $v = @(($c[0]-$a[0]), ($c[1]-$a[1]), ($c[2]-$a[2]))
    $normal = @(($u[1]*$v[2]-$u[2]*$v[1]), ($u[2]*$v[0]-$u[0]*$v[2]), ($u[0]*$v[1]-$u[1]*$v[0]))
    $length = [Math]::Sqrt($normal[0]*$normal[0]+$normal[1]*$normal[1]+$normal[2]*$normal[2])
    if ($length -lt 0.000001) { throw 'Degenerate face' }
    foreach ($point in @($a, $b, $c, $d)) {
        $script:mesh.Add(('v {0} {1} {2}' -f $point[0].ToString('F6',$culture), $point[1].ToString('F6',$culture), $point[2].ToString('F6',$culture)))
    }
    $script:mesh.Add(('vn {0} {1} {2}' -f ($normal[0]/$length).ToString('F6',$culture), ($normal[1]/$length).ToString('F6',$culture), ($normal[2]/$length).ToString('F6',$culture)))
    $first = $script:vertexCount + 1
    $n = $script:normalCount + 1
    $script:mesh.Add(('f {0}/1/{4} {1}/1/{4} {2}/1/{4}' -f $first,($first+1),($first+2),($first+3),$n))
    $script:mesh.Add(('f {0}/1/{4} {2}/1/{4} {3}/1/{4}' -f $first,($first+1),($first+2),($first+3),$n))
    $script:vertexCount += 4
    $script:normalCount++
    if ($script:doubleSidedGauge -and -not $isBackCopy) {
        # Mirror the gauge across the frame's middle (z=0.05), reversing winding.
        $backA = @($a[0], $a[1], (0.1 - $a[2]))
        $backB = @($b[0], $b[1], (0.1 - $b[2]))
        $backC = @($c[0], $c[1], (0.1 - $c[2]))
        $backD = @($d[0], $d[1], (0.1 - $d[2]))
        Add-Quad $backD $backC $backB $backA $true
    }
}

function Write-RingMesh([string]$name, [bool]$isGear, [bool]$isShield = $false) {
    $script:doubleSidedGauge = -not $isGear
    $script:mesh = [Collections.Generic.List[string]]::new()
    $script:mesh.Add('# Generated by tools/GenerateFearWormHpGear.ps1')
    $script:mesh.Add('mtllib HpGear.mtl')
    $script:mesh.Add("o $name")
    $script:mesh.Add('vt 0.5 0.5')
    $script:mesh.Add('usemtl HpGear')
    $script:vertexCount = 0
    $script:normalCount = 0
    $steps = 96
    $start = 0.0
    $sweep = 2.0 * [Math]::PI
    $inner = 4.0
    $outer = 5.3
    $front = -0.18
    $back = 0.28
    if (-not $isGear) {
        $steps = 4
        $sweep = 14.9 * [Math]::PI / 180.0
        $inner = 4.04
        $outer = 4.56
        if ($isShield) {
            $sweep = 9.0 * [Math]::PI / 180.0
            $inner = 4.66
            $outer = 5.06
        }
        $start = [Math]::PI / 2.0 - $sweep / 2.0
        $front = -0.32
        $back = -0.19
    }
    for ($i = 0; $i -lt $steps; $i++) {
        $angleA = $start + $sweep * $i / $steps
        $angleB = $start + $sweep * ($i+1) / $steps
        $radiusA = $outer
        $radiusB = $outer
        if ($isGear) {
            # Twelve broad teeth, with sloped shoulders.
            if (($i % 8) -in @(2,3,4,5)) { $radiusA = 5.9 }
            if ((($i+1) % 8) -in @(2,3,4,5)) { $radiusB = 5.9 }
        }
        $a = New-Point $inner $angleA $front
        $b = New-Point $inner $angleB $front
        $c = New-Point $radiusB $angleB $front
        $d = New-Point $radiusA $angleA $front
        $e = New-Point $inner $angleA $back
        $f = New-Point $inner $angleB $back
        $g = New-Point $radiusB $angleB $back
        $h = New-Point $radiusA $angleA $back
        Add-Quad $a $b $c $d
        Add-Quad $h $g $f $e
        Add-Quad $d $c $g $h
        Add-Quad $b $a $e $f
        if (-not $isGear -and $i -eq 0) { Add-Quad $a $d $h $e }
        if (-not $isGear -and $i -eq ($steps-1)) { Add-Quad $c $b $f $g }
    }
    [IO.File]::WriteAllLines((Join-Path $outputDirectory "$name.obj"), $script:mesh)
}

[IO.File]::WriteAllText((Join-Path $outputDirectory 'HpGear.mtl'), "newmtl HpGear`nKd 1 1 1`nKs 0.5 0.5 0.5`nNs 64`nd 1`n")
Write-RingMesh 'Frame' $true
Write-RingMesh 'HpSegment' $false
Write-RingMesh 'ShieldSegment' $false $true
