"""Build compound boxes from the source parts, preserving arch/rib/rotor openings.

Collider centers and sizes use the scene's X/forward/height ordering, with scale
already applied. rotate_offset lets Object3d rotate each center with its mesh.
"""
import json
from functools import lru_cache
from pathlib import Path

ASSET_DIRECTORY = Path(__file__).resolve().parents[2] / 'resources/Models/Environment/Ocean/UnderwaterProps'
MODEL_PREFIX = 'Environment/Ocean/UnderwaterProps/Runtime/'


def ReadParts(path):
    vertices = []
    parts = {}
    name = ''
    for line in path.read_text(encoding='utf-8').splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append(tuple(map(float, fields[1:4])))
        elif fields[0] == 'o':
            name = fields[1]
            parts[name] = set()
        elif fields[0] == 'f':
            parts[name].update(int(corner.split('/')[0]) - 1 for corner in fields[1:])
    return {name: [vertices[index] for index in sorted(indices)] for name, indices in parts.items()}


@lru_cache(maxsize=None)
def LocalBoxes(asset_id):
    source_id = '04_sunken_rotor' if asset_id.startswith('04_sunken_rotor') else asset_id
    boxes = []
    for name, points in ReadParts(ASSET_DIRECTORY / (source_id + '.obj')).items():
        is_ring = name.startswith(('RingSegment', 'LuminousInlay'))
        if asset_id.endswith('_ring') and not is_ring:
            continue
        if asset_id.endswith('_base') and is_ring:
            continue
        pivot = 3.5 if asset_id.endswith('_ring') else 0.0
        chunks = [points]
        if name.startswith('GiantRib'):
            # Tube(): 11 rings of 7 vertices. Each curved bone gets 10 boxes.
            assert len(points) == 77, (name, len(points))
            chunks = [points[index * 7:(index + 2) * 7] for index in range(10)]
        elif name.startswith('SwayingKelpBlade'):
            # MakeKelp(): 13 cross sections; keep the spaces between blades.
            assert len(points) == 39, (name, len(points))
            chunks = [points[index * 3:(index + 4) * 3] for index in range(0, 12, 3)]
        for chunk in chunks:
            low = [min(point[axis] for point in chunk) for axis in range(3)]
            high = [max(point[axis] for point in chunk) for axis in range(3)]
            # OBJ importer mirrors X. Scene JSON swaps vertical and forward axes.
            center = [-(low[0] + high[0]) / 2, (low[2] + high[2]) / 2,
                      (low[1] + high[1]) / 2 - pivot]
            size = [high[0] - low[0], high[2] - low[2], high[1] - low[1]]
            boxes.append((center, size))
    return boxes


def MakeColliders(obj):
    asset_id = Path(obj['file_name']).stem
    scale = obj['transform']['scale']
    return [{'type': 'BOX', 'rotate_offset': True,
             'center': [round(center[axis] * scale[axis], 5) for axis in range(3)],
             'size': [round(max(size[axis] * abs(scale[axis]), 0.02), 5) for axis in range(3)]}
            for center, size in LocalBoxes(asset_id)]


def Install():
    stage_path = ASSET_DIRECTORY.parents[3] / 'Scenes/stage01.json'
    # Only replace the existing underwater object lines, preserving other data.
    lines = stage_path.read_text(encoding='utf-8').splitlines(keepends=True)
    count = 0
    box_count = 0
    for index, line in enumerate(lines):
        if MODEL_PREFIX not in line:
            continue
        obj = json.loads(line.strip().rstrip(','))
        obj['colliders'] = MakeColliders(obj)
        count += 1
        box_count += len(obj['colliders'])
        lines[index] = '    ' + json.dumps(obj, ensure_ascii=False) + ',\n'
    assert count == 42, count
    stage_path.write_text(''.join(lines), encoding='utf-8')
    report_path = ASSET_DIRECTORY / 'placement_info.json'
    report = json.loads(report_path.read_text(encoding='utf-8'))
    report['collidersAdded'] = box_count
    report['colliderSource'] = 'stage01.json; generated by UnderwaterPropColliders.py'
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'Installed compound colliders: {count} objects, {box_count} boxes')


if __name__ == '__main__':
    Install()
